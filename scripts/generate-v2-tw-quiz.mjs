import fs from 'node:fs';
import path from 'node:path';

const SOURCE_FILE = process.env.V2_TW_QUESTION_FILE || '/Users/pensoair/Library/Mobile Documents/iCloud~md~obsidian/Documents/Penso-OS/07_專案工坊/Subdomain_kiwimu.com/Kiwimu_MBTI_Lab_內容庫/2026_H1_跨國升級版/MBTI_Question_Bank_2026_Taiwan.md';
const OUTPUT_FILE = path.resolve(process.cwd(), 'data/v2TaiwanQuestions.generated.ts');

const DIMENSION_VALUE_MAP = {
  EI: ['E', 'I'],
  SN: ['S', 'N'],
  TF: ['T', 'F'],
  JP: ['J', 'P'],
  AT: ['A', 'Turbulent'],
};

function assert(value, message) {
  if (!value) {
    throw new Error(message);
  }
  return value;
}

function parseRow(line) {
  const cells = line
    .split('|')
    .slice(1, -1)
    .map((cell) => cell.trim());

  if (cells.length !== 7) {
    throw new Error(`Unexpected table shape: ${line}`);
  }

  return {
    questionId: cells[0],
    country: cells[1],
    dimension: cells[2],
    context: cells[3],
    optionA: cells[4],
    optionB: cells[5],
    culturalNote: cells[6],
  };
}

function buildQuestionRecord(row) {
  const index = Number(row.questionId.replace('Q', ''));
  const pair = assert(DIMENSION_VALUE_MAP[row.dimension], `Unknown dimension: ${row.dimension}`);

  return {
    id: index,
    questionId: row.questionId,
    country: row.country,
    dimension: row.dimension,
    text: row.context,
    options: [
      { id: 'a', label: row.optionA, value: pair[0] },
      { id: 'b', label: row.optionB, value: pair[1] },
    ],
    culturalNote: row.culturalNote,
    weight: (index - 1) % 8 === 0 ? 2 : 1,
  };
}

function quote(value) {
  return JSON.stringify(value);
}

function formatQuestion(question) {
  return `  {
    id: ${question.id},
    questionId: ${quote(question.questionId)},
    country: ${quote(question.country)},
    dimension: ${quote(question.dimension)},
    text: ${quote(question.text)},
    options: [
      { id: 'a', label: ${quote(question.options[0].label)}, value: ${quote(question.options[0].value)} },
      { id: 'b', label: ${quote(question.options[1].label)}, value: ${quote(question.options[1].value)} },
    ],
    culturalNote: ${quote(question.culturalNote)},
    weight: ${question.weight},
  }`;
}

function main() {
  const markdown = fs.readFileSync(SOURCE_FILE, 'utf8');
  const questionRows = markdown
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => /^\|\s*Q\d+/u.test(line))
    .map(parseRow)
    .map(buildQuestionRecord);

  assert(questionRows.length === 40, `Expected 40 Taiwan questions, received ${questionRows.length}`);

  const output = `/* eslint-disable */\n// Auto-generated by scripts/generate-v2-tw-quiz.mjs\n// Source: ${SOURCE_FILE}\n\nexport type V2QuestionDimension = 'EI' | 'SN' | 'TF' | 'JP' | 'AT';\nexport type V2QuestionValue = 'E' | 'I' | 'S' | 'N' | 'T' | 'F' | 'J' | 'P' | 'A' | 'Turbulent';\n\nexport interface V2GeneratedQuestionOption {\n  id: 'a' | 'b';\n  label: string;\n  value: V2QuestionValue;\n}\n\nexport interface V2GeneratedQuestion {\n  id: number;\n  questionId: string;\n  country: string;\n  dimension: V2QuestionDimension;\n  text: string;\n  options: [V2GeneratedQuestionOption, V2GeneratedQuestionOption];\n  culturalNote: string;\n  weight: number;\n}\n\nexport const V2_TW_QUESTION_SOURCE = ${quote(SOURCE_FILE)};\n\nexport const V2_TAIWAN_QUESTIONS: V2GeneratedQuestion[] = [\n${questionRows.map(formatQuestion).join(',\n')}\n];\n`;

  fs.writeFileSync(OUTPUT_FILE, output, 'utf8');
  console.log(`Generated ${questionRows.length} Taiwan V2 questions -> ${OUTPUT_FILE}`);
}

main();
